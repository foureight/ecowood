		<h2 class="green">Kompostárna ECOWOOD leží mezi Unhoští a Pavlovem</h2>
		<p class="lead">Kompostárna <b>ECOWOOD</b> leží u silnice III/0067 mezi Unhoští a Pavlovem na Kladensku. Přijímáme a zpracováváme biologicky rozložitelný odpad pro domácnosti, firmy, obce i zahradníky a v areálu prodáváme kompost a substráty.</p>
		<p>Přivézt k nám můžete zejména trávu, listí, větve, dřevo a další rostlinný odpad. Bioodpad zpracujeme a vrátíme zpět do přírodního koloběhu v podobě kompostu, zahradnických substrátů a zemin.</p>

